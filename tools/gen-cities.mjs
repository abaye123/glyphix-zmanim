// Generates src/lib/cities.js from tools/cities.csv and the reference refraction.
import { readFileSync, writeFileSync } from 'node:fs'
import { refraction } from './reference.mjs'

const rows = readFileSync(new URL('./cities.csv', import.meta.url), 'utf8').trim().split(/\r?\n/)
const r = v => Number(v.toFixed(5))
// Minutes before sunset; every other city uses 18.
const CANDLES = { 'ירושלים': 40, 'אלעד': 30, 'בני ברק': 20 }
const cities = rows.map(line => {
  const [name, lat, lon, elev] = line.split(',')
  const e = Number(elev)
  return {
    name, lat: Number(lat), lon: Number(lon), candles: CANDLES[name] || 18,
    ref: [r(refraction(e, true, true)), r(refraction(e, true, false)), r(refraction(e, false, true)), r(refraction(e, false, false))],
  }
})
const body = cities.map(c => '  ' + JSON.stringify(c)).join(',\n')
writeFileSync(new URL('../src/lib/cities.js', import.meta.url),
  '// Generated by tools/gen-cities.mjs. ref: horizon refraction in degrees, [winter am, winter pm, summer am, summer pm].\n' +
  'export const CITIES = [\n' + body + '\n]\n')
console.log(cities.length, 'cities;', JSON.stringify(cities[0]))
